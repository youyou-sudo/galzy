import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, basename, relative } from "node:path";
import { scanServerFns } from "./lib/scan-server-fns.mjs";

const root = "apps/web-tanstack/src";
const targets = process.argv.slice(2);
const files = targets.length ? targets : [];
const registryImports = [];
const registryEntries = [];

for (const rel of files) {
  const abs = join(root, rel);
  const src = readFileSync(abs, "utf8");
  const fns = scanServerFns(src, abs);
  if (!fns.length) { console.log("skip (no fns)", rel); continue; }
  const domain = rel.replace(/^server\//, "").replace(/\.ts$/, "").replace(/\/index$/, "").replace(/\//g, ".");
  const implRel = rel.replace(/^server\//, "server/impl/").replace(/\.ts$/, ".ts");
  const implAbs = join(root, implRel);
  mkdirSync(dirname(implAbs), { recursive: true });

  // build impl source by replacing each createServerFn chain
  let impl = src;
  const sorted = [...fns].sort((a, b) => b.start - a.start);
  const usesNoInput = fns.some((f) => !f.validator);
  const usesInput = fns.some((f) => f.validator);
  for (const fn of sorted) {
    const replacement = fn.validator ? "defineBff(" + fn.validator + ", " + fn.handler + ")" : "defineBffNoInput(" + fn.handler + ")";
    impl = impl.slice(0, fn.start) + replacement + impl.slice(fn.end);
  }
  impl = impl.replace(/import \{ createServerFn \} from ["']@tanstack\/react-start["'];?\n?/, "");
  const imports = ["/import \"@teyik0\\/furin\\/server-only\";\n/"];
  impl = impl.replace(/^(\s*)/, "import \"@teyik0/furin/server-only\";\n" + (usesInput && usesNoInput ? "import { defineBff, defineBffNoInput } from \"@web/lib/bff/define\";\n" : usesInput ? "import { defineBff } from \"@web/lib/bff/define\";\n" : "import { defineBffNoInput } from \"@web/lib/bff/define\";\n"));

  // stub: surface with bffFn delegates + type re-exports
  const stub = [];
  stub.push("import { bffFn } from \"@web/lib/bff/fn\";");
  const relImport = "./" + relative(dirname(abs), implAbs).split("\\").join("/").replace(/\.ts$/, "");
  stub.push("import type * as impl from \"" + relImport + "\";");
  stub.push("");
  for (const fn of fns) {
    stub.push("export const " + fn.name + " = bffFn<typeof impl." + fn.name + ">(\"" + domain + "." + fn.name + "\");");
  }
  stub.push("");
  stub.push("export type * from \"" + relImport + "\";");
  stub.push("");

  writeFileSync(implAbs, impl);
  writeFileSync(abs, stub.join("\n"));
  registryImports.push("import * as " + domain.replace(/\./g, "_") + " from \"@web/server/impl/" + rel.replace(/^server\//, "").replace(/\.ts$/, "") + "\";");
  for (const fn of fns) registryEntries.push("\t\"" + domain + "." + fn.name + "\": " + domain.replace(/\./g, "_") + "." + fn.name + ",");
  console.log("migrated", rel, "fns:", fns.length);
}

if (registryImports.length) {
  const reg = [];
  reg.push("import \"@teyik0/furin/server-only\";");
  for (const line of registryImports) reg.push(line);
  reg.push("import type { BffImplLike } from \"@web/lib/bff/protocol\";");
  reg.push("");
  reg.push("/**");
  reg.push(" * Server-side registry of every BFF handler.");
  reg.push(" * Generated by scripts/furin/migrate-server-fns.mjs; keep in sync when adding handlers.");
  reg.push(" */");
  reg.push("export const bffRegistry: Record<string, BffImplLike> = {");
  for (const line of registryEntries) reg.push(line);
  reg.push("};");
  reg.push("");
  writeFileSync(join(root, "server/registry.ts"), reg.join("\n"));
  console.log("registry entries:", registryEntries.length);
}
#!/usr/bin/env bun
/**
 * 把 Nitro（bun preset）产物 + 静态资源编译成单文件可执行程序。
 *
 * 前置：`bun run build` 已产出 .output/{server,public}。
 * 输出：.output/server-bin（Windows 下为 .output/server-bin.exe）。
 *
 * 资源内嵌方式（参考 TanStack Router examples/react/start-bun）：
 *   - 生成 .assets.generated.ts，用 `with { type: "file" }` 引入 .output/public 下每个文件；
 *   - `--asset-naming="[dir]/[name].[ext]"` 保留相对路径，Nitro 运行时按
 *     <root>/.output/public/... 从二进制内读取（见 server-prod.ts）；
 *   - 最终产物是单个可执行文件（Bun 运行时 + 服务端代码 + 全部静态资源）。
 */

import { Glob } from "bun";
import { existsSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dir, "..");
process.chdir(ROOT);

const OUTPUT_DIR = path.join(ROOT, ".output");
const PUBLIC_DIR = path.join(OUTPUT_DIR, "public");
const SERVER_ENTRY = path.join(OUTPUT_DIR, "server", "index.mjs");
const GENERATED = path.join(ROOT, ".assets.generated.ts");
const OUTFILE = path.join(
	OUTPUT_DIR,
	process.platform === "win32" ? "server-bin.exe" : "server-bin",
);

function fail(message: string): never {
	console.error(`[build-binary] ${message}`);
	process.exit(1);
}

if (!existsSync(SERVER_ENTRY)) {
	fail("未找到 .output/server/index.mjs，请先运行 bun run build");
}
if (!existsSync(PUBLIC_DIR)) {
	fail("未找到 .output/public，请检查构建产物");
}

// ── 收集 .output/public 下的所有文件 ─────────────────────────
const files: string[] = [];
// dot: true —— .output/public 下还有 .vite/（ssr-manifest 等）点目录，
// 默认扫描会跳过它，二进制里就会缺文件（磁盘版 200、二进制 500）。
for await (const relative of new Glob("**/*").scan({
	cwd: PUBLIC_DIR,
	onlyFiles: true,
	dot: true,
})) {
	files.push(relative.split(path.sep).join("/"));
}
files.sort();
if (files.length === 0) {
	fail(".output/public 为空，无法内嵌静态资源");
}

// ── 生成资源清单（URL 路径 -> 内嵌文件） ─────────────────────
const source = ["// AUTO-GENERATED by scripts/build-binary.ts — do not edit.", ""];
const entries: string[] = [];
files.forEach((relative, index) => {
	source.push(
		`import a${index} from "./.output/public/${relative}" with { type: "file" };`,
	);
	entries.push(`\t"/${relative}": a${index},`);
});
source.push("");
source.push(
	"// URL 路径 -> 二进制内嵌文件路径（仅用于排查；Nitro 通过 __nitro_main__ 读取）",
);
source.push("export const assetPaths: Record<string, string> = {");
source.push(...entries);
source.push("};");
source.push(`export const assetCount = ${files.length};`, "");
await Bun.write(GENERATED, source.join("\n"));
console.log(
	`[build-binary] 内嵌 ${files.length} 个静态资源 -> .assets.generated.ts`,
);

// ── 编译单文件可执行程序 ─────────────────────────────────────
const result = Bun.spawnSync(
	[
		"bun",
		"build",
		"--compile",
		"--target=bun",
		"--asset-naming=[dir]/[name].[ext]",
		"server-prod.ts",
		"--outfile",
		OUTFILE,
	],
	{ stdio: ["inherit", "inherit", "inherit"], cwd: ROOT },
);

if (result.exitCode !== 0) {
	fail(`bun build --compile 失败（exit ${result.exitCode}）`);
}

const sizeMb = (Bun.file(OUTFILE).size / 1024 / 1024).toFixed(1);
console.log(
	`[build-binary] 完成：${path.relative(ROOT, OUTFILE)} (${sizeMb} MB)`,
);
